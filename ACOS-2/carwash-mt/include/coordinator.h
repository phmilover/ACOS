/**
 * @file coordinator.h
 * @brief Поток координатора: прибытия машин, закрытие въезда, сбор потоков машин.
 */
#ifndef COORDINATOR_H
#define COORDINATOR_H

/// Размер стека потока машины: машине хватает малого, а потоков может быть много.
#define CAR_STACK_SIZE ((size_t)256 * 1024)

/**
 * @brief Тело потока координатора.
 *
 * Въезд открыт с минуты 0. По интервалам прибытия создаёт поток машины; закрывает въезд
 * (EV_CLOSE) в конце дня или когда последняя машина дня принята или получила отказ (ждёт её в
 * SimPark, будит машина); собирает (pthread_join) потоки
 * уехавших и получивших отказ. Не удалось создать машину или её поток - выставляет запрос
 * REQ_NO_RESOURCES и выходит. После закрытия въезда поток завершается.
 * @param arg Line *
 */
void *CoordinatorMain(void *arg);

#endif
