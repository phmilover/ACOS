/**
 * @file render.h
 * @brief Поток отрисовки живой схемы: кадры передаются через два буфера, монитор «ограниченный
 * буфер».
 *
 * Крючок часов кладёт снимок (RenderSubmit), поток отрисовки рисует его (ViewLiveDraw). Два
 * буфера Snapshot по кругу под одним мьютексом (RANK_RENDER) и три условные переменные: notFull
 * (есть пустой буфер), notEmpty (есть кадр), drained (все отданные кадры нарисованы). Submit
 * ждёт notFull, копирует снимок в очередной буфер, будит notEmpty; поток отрисовки ждёт
 * notEmpty, рисует буфер уже без мьютекса и только потом возвращает его (будит notFull). Пока
 * рисуется кадр в одном буфере, крючок кладёт следующий в другой и не ждёт; ждёт только третий
 * кадр. Медленный терминал поэтому притормаживает часы не больше чем на кадр, а модель внутри
 * минуты не держит: пока кадр рисуется, потоки модели продолжают работать.
 *
 * Поток отрисовки - не поток модели: в часах он не зарегистрирован и модель не держит.
 */
#ifndef RENDER_H
#define RENDER_H

#include "snapshot.h"

/// Готовит монитор и запускает поток отрисовки. Повторный вызов при работающем потоке ничего не
/// делает. @return 0 или -1 (не создалась условная переменная или поток; всё созданное убрано)
int RenderStart(void);

/// @return 1, если поток отрисовки запущен (RenderStart удался, RenderStop ещё не звали)
int RenderActive(void);

/// Отдаёт кадр потоку отрисовки: ждёт свободного буфера (оба заняты - пока не дорисуется
/// более ранний кадр) и копирует снимок.
/// Звать из одного потока (крючок часов). Без RenderStart ничего не делает.
void RenderSubmit(const Snapshot *s);

/// Ждёт, пока поток отрисовки дорисует все отданные кадры: после этого можно печатать в терминал
/// своё, не боясь перемешать вывод.
void RenderFlush(void);

/// Будит поток отрисовки, дожидается его выхода (отданные кадры дорисовываются) и убирает
/// монитор. Не зависает, даже если поток ждёт кадр. Без RenderStart ничего не делает.
void RenderStop(void);

#endif
