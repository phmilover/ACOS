/**
 * @file coordinator.h
 * @brief Поток координатора: прибытия машин, закрытие въезда, сбор потоков машин.
 */
#ifndef COORDINATOR_H
#define COORDINATOR_H

/**
 * @brief Тело потока координатора.
 *
 * Первым делом ждёт на барьере старта (Line.start), затем SimBegin. Въезд открыт с минуты 0.
 * По интервалам прибытия создаёт поток машины (ThreadCreate со стеком CAR_STACK_SIZE);
 * закрывает въезд (EV_CLOSE) в конце дня или когда последняя машина дня принята или получила
 * отказ (ждёт её на Line.decided с мьютексом Line.entrance, будит машина); собирает
 * (pthread_join) потоки уехавших и получивших отказ. Не удалось создать машину или её поток -
 * выставляет запрос REQ_NO_RESOURCES и выходит. После закрытия въезда поток завершается.
 * @param arg Line *
 */
void *CoordinatorMain(void *arg);

#endif
