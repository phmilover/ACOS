#ifndef POST_H
#define POST_H

/**
 * @brief Тело потока поста.
 *
 * Первым делом ждёт на барьере старта (Line.start), затем SimBegin. Раз в минуту (с минуты 1)
 * под мьютексом своей стадии: идёт ремонт - минута ремонта, на последней EV_REPAIR и
 * StageRepaired; исправный пост без брони может сломаться (EV_FAIL, машинам на нём - причина
 * WAIT_REPAIR); исправный пост работает - у каждой машины на нём минус минута операции, на
 * нуле EV_OP_END, и машины поста будятся (StageWakePost). Саботаж SAB_RACE: сразу после
 * пробуждения, до мьютекса стадии, Line.raceTicks++ без мьютекса (гонка для ThreadSanitizer).
 * @param arg Post * из линии (Post.line задан)
 */
void *PostMain(void *arg);

#endif
