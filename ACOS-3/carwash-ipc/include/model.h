/**
 * @file model.h
 * @brief Поведение участников программ 1-3 поверх разделяемой памяти и семафоров.
 *
 * Каждая функция M* - тело одного процесса: машины, поста, источника машин или координатора.
 * Программы 1 и 2 запускают эти тела в дочерних процессах (fork), программа 3 - в отдельных
 * независимо запущенных программах.
 *
 * Как семафоры связывают участников:
 *  - SEM_MUTEX     - все изменения State и вывод события идут под ним, поэтому лента
 *                    упорядочена так же, как менялось состояние;
 *  - SEM_QUEUE(s)  - машина берёт место в накопителе стадии s, прежде чем уйти с поста;
 *                    если мест нет, она ждёт на посту и держит его (затор назад по линии);
 *  - SEM_WORK(s)   - сколько машин ждут пост стадии s; свободный пост ждёт на нём;
 *  - SEM_CAR(c)    - пост будит машину: «заезжай» и «операция закончена»;
 *  - SEM_POST(s,p) - машина сообщает посту, что съехала с него;
 *  - SEM_COORD     - будит координатора, когда что-то закончилось.
 */
#ifndef MODEL_H
#define MODEL_H

#include "ipc.h"

void MLock(Ipc *ipc);
void MUnlock(Ipc *ipc);
/// sem_post по номеру семафора.
void MSignal(Ipc *ipc, int sem);
/**
 * @brief sem_wait с обработкой сигналов.
 * @return 0 - дождались, -1 - имитация останавливается (процессу пора выходить)
 */
int MWait(Ipc *ipc, int sem);
/// Ждёт @p minutes минут модели. @return 0 или -1 (имитация останавливается)
int MSleep(Ipc *ipc, int minutes);
/// Обрабатывает флаги сигналов: SIGINT/SIGTERM - остановка, SIGUSR1 - состояние, SIGUSR2 -
/// закрыть въезд. Нельзя звать под SEM_MUTEX.
void MHandleSignals(Ipc *ipc);
/// Просит всех остановиться (первая причина побеждает) и будит координатора.
void MRequestStop(Ipc *ipc, StopReason why);
/// Координатор: будит всех, кто ждёт на семафорах, чтобы они увидели stop и вышли.
void MWakeAll(Ipc *ipc);

/// Тело процесса машины в ячейке @p slot (ячейку заранее резервирует источник машин).
/// @return код выхода процесса
int MCar(Ipc *ipc, int slot);
/// Тело процесса поста @p post стадии @p stage. @return код выхода процесса
int MPost(Ipc *ipc, int stage, int post);

/// Запуск процесса машины для зарезервированной ячейки. @return 0 или -1
typedef int (*SpawnCar)(Ipc *ipc, int slot);
/// Источник машин: приезд с интервалами, закрытие въезда по времени, числу машин или SIGUSR2.
void MArrivals(Ipc *ipc, SpawnCar spawn);
/// Координатор: ждёт, пока въезд закрыт и линия пуста, или пока не попросили остановиться.
StopReason MAwaitEnd(Ipc *ipc);

/**
 * @brief Независимый процесс подключается к объектам координатора по ключу.
 *
 * Координатор мог ещё не запуститься или не создать все семафоры, поэтому попытки
 * повторяются до @p seconds секунд (Ctrl+C прерывает ожидание).
 * @return 0 или -1 (сообщение уже в stderr)
 */
int MAttach(Ipc *ipc, const char *key, int seconds, const char *prog);
/// Открывает журнал координатора на дозапись и настраивает вывод событий. @return 0 или -1
int MOpenJournal(Ipc *ipc);

#endif
