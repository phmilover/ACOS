/**
 * @file render.h
 * @brief Поток отрисовки живой схемы: кадры передаются через два буфера и два семафора.
 *
 * Крючок часов кладёт снимок (RenderSubmit), поток отрисовки рисует его (ViewLiveDraw). Два
 * буфера Snapshot, семафоры free (начальное значение 1) и ready (0): Submit ждёт free, копирует
 * снимок в буфер, будит ready; поток отрисовки ждёт ready, рисует, возвращает free. Медленный
 * терминал поэтому притормаживает часы (следующий кадр ждёт предыдущий), но не модель внутри
 * минуты: пока кадр рисуется, потоки модели продолжают работать.
 *
 * Поток отрисовки - не поток модели: в часах он не зарегистрирован и модель не держит.
 */
#ifndef RENDER_H
#define RENDER_H

#include "snapshot.h"

/// Открывает семафоры и запускает поток отрисовки. Повторный вызов при работающем потоке ничего
/// не делает. @return 0 или -1 (не открылся семафор или не создался поток; всё открытое закрыто)
int RenderStart(void);

/// @return 1, если поток отрисовки запущен (RenderStart удался, RenderStop ещё не звали)
int RenderActive(void);

/// Отдаёт кадр потоку отрисовки: ждёт, пока он закончит предыдущий кадр, и копирует снимок.
/// Звать из одного потока (крючок часов). Без RenderStart ничего не делает.
void RenderSubmit(const Snapshot *s);

/// Ждёт, пока поток отрисовки дорисует отданный кадр: после этого можно печатать в терминал
/// своё, не боясь перемешать вывод.
void RenderFlush(void);

/// Будит поток отрисовки, дожидается его выхода (отданный кадр дорисовывается) и закрывает
/// семафоры. Не зависает, даже если поток ждёт кадр. Без RenderStart ничего не делает.
void RenderStop(void);

#endif
