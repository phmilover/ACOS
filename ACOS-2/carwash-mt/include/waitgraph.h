/**
 * @file waitgraph.h
 * @brief Граф ожидания (текст и Graphviz DOT) и таблица потоков модели.
 *
 * Граф строится по состоянию стадий: кто стоит на постах и в очередях и кто записан в
 * списки ожидающих места. Цепочка «машина -> ждёт место на стадии -> стадию держат такие-то
 * машины -> они ждут ...» идёт вперёд по линии и кончается корневой причиной: стадия без
 * постов, все посты стадии сломаны, стадия забита заблокированными машинами.
 *
 * Звать только в момент покоя (из крючка часов) или когда других потоков нет: функции берут
 * мьютексы стадий по одному и читают состояние, которое в покое не меняется.
 */
#ifndef WAITGRAPH_H
#define WAITGRAPH_H

#include "config.h"
#include "line.h"

/**
 * @brief Печатает граф ожидания текстом:
 *
 *     WAITS-FOR GRAPH at 09:46 (10 car(s) stuck)
 *       car #15  on tunnel post 1   -> waits for room in wax
 *         wax: 0 posts                <- ROOT CAUSE: stage wax has no posts
 *
 * Машины сгруппированы по стадии, которую ждут (дальние по линии - первыми), под группой -
 * строка о состоянии этой стадии. Моющиеся машины не ждут и в список не попадают.
 * @param fd куда печатать @param l линия @param color 1 - выделить цветом (ANSI)
 */
void WaitGraphPrint(int fd, Line *l, int color);

/// Пишет тот же граф в формате Graphviz DOT (машины - овалы, стадии - прямоугольники,
/// корневая причина - красным). @return 0 или -1, если файл не открылся
int WaitGraphDot(Line *l, const char *path);

/// Таблица потоков модели (SimForEach): первая строка начинается с "THREADS" и считает потоки
/// по видам и состояниям, далее по строке на поток: имя, состояние, чего ждёт.
/// @param cfg имена стадий для причин ожидания
void WaitGraphThreads(int fd, const Config *cfg);

#endif
