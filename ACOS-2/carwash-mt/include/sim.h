/**
 * @file sim.h
 * @brief Виртуальные часы и парковка потоков модели (обычный режим и -D).
 *
 * Каждый поток модели в каждый момент либо работает, либо припаркован: спит до модельной
 * минуты (SimSleep) или ждёт другого потока (SimPark). Часы переводят стрелку, только когда
 * работающих нет и запускать некого (момент покоя). Перед переводом часы вызывают крючок:
 * в нём состояние модели устойчиво.
 *
 * Тот, кто будит (SimWake), сам увеличивает счётчик работающих до sem_post, поэтому часы
 * не проскакивают. Если поток разбудили, пока он ещё работает (проверил условие, но не успел
 * запарковаться), пробуждение запоминается, и его ближайший SimPark возвращается сразу -
 * пробуждения не теряются. Поэтому SimPark может вернуться «зря»: условие ожидания
 * проверяют в цикле, как у условной переменной.
 *
 * Режимы:
 * - обычный: все, кому пора, запускаются сразу и работают параллельно;
 * - детерминированный (-D): работает не больше одного потока модели. Проснувшиеся в одну
 *   минуту запускаются по возрастанию order, разбуженные SimWake и порождённые SimSpawned
 *   встают в очередь FIFO и запускаются по одному, когда текущий паркуется.
 *
 * Порядок запуска (контракт): SimInit, затем для каждого начального потока SimThreadInit,
 * SimSpawned и pthread_create, и только потом - pthread_create(SimClockMain). Иначе часы
 * могут увидеть «покой» до появления потоков и закончить модель на минуте 0.
 *
 * Все поля SimThread, кроме kind/id/name/order (они задаются при создании), меняются только
 * под мьютексом часов (ранг RANK_SIM).
 */
#ifndef SIM_H
#define SIM_H

#include "sem.h"

/// Потоки модели (часы, сигналы, отрисовка не регистрируются).
typedef enum { TH_COORD, TH_CAR, TH_POST } ThreadKind;

/// Состояние потока модели. До SimSpawned и после SimExit - ST_DONE.
typedef enum { ST_READY, ST_RUNNING, ST_SLEEPING, ST_PARKED, ST_DONE } SimState;

/// Чего ждёт припаркованный поток (для графа ожидания и панели потоков).
typedef enum { WAIT_NONE, WAIT_TIME, WAIT_QUEUE, WAIT_OPERATION, WAIT_ROOM, WAIT_REPAIR } WaitKind;

/// Причина ожидания: вид, стадия и пост (если не нужны - любые).
typedef struct {
    WaitKind kind;
    int stage;
    int post;
} WaitReason;

/// Поток модели с точки зрения часов.
typedef struct SimThread {
    ThreadKind kind;
    int id;
    char name[24];
    int order;  ///< порядок пробуждения в одну минуту в -D (меньше - раньше)
    Sem wake;   ///< на нём поток ждёт, пока его запустят
    SimState state;
    int wakeAt;             ///< минута пробуждения спящего
    WaitReason why;         ///< причина ожидания
    int wakePending;        ///< разбудили, пока работал: ближайший SimPark проходит сразу
    int reasonPending;      ///< причину задали, пока работал: ближайший SimPark берёт её
    WaitReason pendingWhy;  ///< эта причина
    long parks;             ///< сколько раз вызывал SimPark
    struct SimThread *nextAll, *nextReady;
} SimThread;

/// Итог ожидания: SIM_STOP значит, что модель останавливается и поток должен выйти.
typedef enum { SIM_OK, SIM_STOP } SimStatus;

/// Вызывается потоком часов, когда никто не работает и некого запускать, до перевода стрелки
/// (в том числе на минуте 0). Мьютекс часов при вызове не захвачен.
/// @param now текущая минута @param nextWake ближайшее время пробуждения спящих или -1
/// @param ctx SimOptions.ctx
/// @return 0 - остановить модель; 1 - продолжать (при nextWake == -1 часы ждут, пока
/// кто-нибудь не разбудит поток извне)
typedef int (*SimHook)(int now, int nextWake, void *ctx);

/// Параметры модели.
typedef struct {
    int deterministic;  ///< режим -D
    int delayMs;        ///< задержка перед переводом стрелки (темп показа), 0 - без неё
    SimHook hook;       ///< крючок момента покоя; NULL - продолжать, пока есть спящие
    void *ctx;          ///< передаётся в крючок
} SimOptions;

/// Готовит новую модель: минута 0, нет потоков, снят флаг остановки. Можно звать повторно,
/// когда потоки прошлой модели уже собраны (join) и уничтожены.
/// @return 0 или -1, если не открылся семафор часов
int SimInit(const SimOptions *o);

/// Регистрирует поток (состояние ST_DONE до SimSpawned).
/// @param name имя для панели и LOCKDEP (обрезается до 23 символов)
/// @return 0 или -1, если не открылся семафор
int SimThreadInit(SimThread *t, ThreadKind kind, int id, const char *name, int order);

/// Снимает регистрацию и закрывает семафор. Поток должен быть в ST_DONE (собран).
void SimThreadDestroy(SimThread *t);

/// Зовёт создатель до pthread_create: поток становится ST_READY и встаёт в очередь запуска.
void SimSpawned(SimThread *t);

/// Первая строка тела потока: ждёт, пока его запустят.
SimStatus SimBegin(SimThread *self);

/// Последняя строка тела потока: ST_DONE, поток больше не считается работающим.
void SimExit(SimThread *self);

/// Спит @p minutes ≥ 1 модельных минут (SimWake сон не прерывает).
SimStatus SimSleep(SimThread *self, int minutes);

/// Паркуется до SimWake. @param why причина ожидания; если до парковки другой поток уже
/// задал причину через SimSetReason, остаётся она, а @p why не используется. Запомненная
/// причина относится только к ближайшему ожиданию: её сбрасывают SimPark (и при возврате
/// сразу по запомненному SimWake), SimSleep и SimExit
SimStatus SimPark(SimThread *self, WaitReason why);

/// Меняет причину ожидания: припаркованному - сразу; работающему или готовому - запоминает
/// для его ближайшего SimPark (иначе устаревший аргумент SimPark затёр бы её).
void SimSetReason(SimThread *t, WaitReason why);

/// Будит поток: припаркованный - в очередь запуска; работающему запоминает пробуждение для
/// ближайшего SimPark; спящему (проснётся по времени), готовому и завершённому - ничего.
/// Можно звать из любого потока.
void SimWake(SimThread *t);

/// @return текущая модельная минута
int SimNow(void);

/// Останавливает модель: будит всех ждущих (их Sim* возвращают SIM_STOP), дальнейшие вызовы
/// Sim* сразу возвращают SIM_STOP, поток часов выходит. Можно звать из любого потока.
void SimStop(void);

/// @return 1, если модель останавливается
int SimStopping(void);

/// Тело потока часов; возвращается после остановки. @param unused не используется
void *SimClockMain(void *unused);

/// Обходит все зарегистрированные потоки. Звать только из крючка. @p fn вызывается под
/// мьютексом часов: в нём нельзя звать Sim* и брать мьютексы рангом не выше RANK_SIM.
void SimForEach(void (*fn)(const SimThread *t, void *ctx), void *ctx);

/// @return сколько раз за модель вызывали SimPark (все потоки)
long SimTotalParks(void);

#endif
