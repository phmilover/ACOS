/**
 * @file auditor.h
 * @brief Аудитор инвариантов: восстанавливает линию только по событиям и проверяет её.
 *
 * Инварианты варианта 43:
 *  - I1 на посту не больше машин, чем его ёмкость;
 *  - I2 машина ровно в одном месте (очередь или пост; между EV_LEAVE и EV_MOVE/EV_DONE - в
 *    пути, и тогда больше нигде);
 *  - I3 стадии идут в порядке программы;
 *  - I4 сломанный пост не начинает операцию;
 *  - I5 очередь не переполнена.
 *
 * Живое состояние линии аудитор не читает (его меняют другие потоки): место каждой машины,
 * занятость постов, длину очередей, поломки и пройденные шаги маршрута он ведёт сам. События
 * одной машины идут в порядке EV_LEAVE (с поста s) ... EV_MOVE (на n, arg = s), затем
 * EV_ENTER/EV_QUEUE на n; между ними бывают события других машин.
 *
 * Потоки: AuditorListener зовёт шина под своим мьютексом, по одному событию, поэтому
 * состояние аудитора своих мьютексов не требует. AuditorPrint/AuditorFree - после сбора всех
 * потоков модели.
 */
#ifndef AUDITOR_H
#define AUDITOR_H

#include "config.h"
#include "events.h"

/// Готовит пустой учёт. @param errFd куда печатать нарушения (обычно 2)
/// @param cfg стадии и программы; живёт дольше аудитора
void AuditorInit(int errFd, const Config *cfg);

/// Подписчик шины: обновляет свой учёт и проверяет инварианты.
void AuditorListener(const Event *e);

/// Итоговый отчёт: сколько проверок и какие инварианты нарушались.
void AuditorPrint(int fd);
void AuditorFree(void);

long AuditorChecks(void);      ///< сколько событий проверено
long AuditorViolations(void);  ///< сколько нарушений найдено (больше 0 - код выхода 4)

#endif
